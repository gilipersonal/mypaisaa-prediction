// The app's styles are the design's styles, in the design's order (MP-205, design parity).
//
// docs/design/journeys/build.py builds the Journeys page from Prism's <style> block, the shared Claude components,
// src/shell.css and each journey's own css, in that order. This writes the same sheet, byte for byte, to
// src/lib/prism/design.generated.css (git-ignored), so every rule the app draws with is the design's own and cascades
// as it does on the design page. Nothing is copied by hand. With --check it fails if the written sheet is stale.
// Fails closed: a source it cannot read or a block it cannot find stops the build (exit 2).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const design = join(web, '..', 'docs', 'design');
const OUT = join(web, 'src', 'lib', 'prism', 'design.generated.css');
/* the Journeys build's order (build.py ORDER) */
const ORDER = ['home', 'holdings', 'forecast', 'research', 'journal', 'track', 'cost', 'approvals', 'privacy', 'peek'];

/** @param {string} html @param {string} name @returns {string} */
function styleOf(html, name) {
  const m = /<style>([\s\S]*?)<\/style>/.exec(html);
  if (!m || m[1] === undefined) throw new Error(`design-css: no <style> block in ${name}`);
  return m[1];
}

/** The sheet the Journeys page draws with. @returns {string} */
export function designCss() {
  const prism = styleOf(readFileSync(join(design, 'prism', 'index.html'), 'utf8'), 'prism/index.html');
  const claude = styleOf(readFileSync(join(design, 'reviews', 'MP-62', 'shared', 'claude.html'), 'utf8'), 'claude.html');
  const shell = readFileSync(join(design, 'journeys', 'src', 'shell.css'), 'utf8');
  const journeys = ORDER.map((k) => join(design, 'journeys', 'src', 'journeys', `${k}.css`)).filter((p) => existsSync(p)).map((p) => readFileSync(p, 'utf8')).join('\n');
  return `/* Generated by web/scripts/design-css.mjs from docs/design (Prism, Claude, Journeys). Do not edit. */\n${prism}\n${claude}\n${shell}${journeys}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    const css = designCss();
    if (process.argv.includes('--check')) {
      const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
      if (now !== css) { console.error('design-css: src/lib/prism/design.generated.css is stale; run node scripts/design-css.mjs'); process.exit(1); }
      console.log('design-css: the app draws with the design\'s own sheet');
    } else {
      mkdirSync(dirname(OUT), { recursive: true });
      writeFileSync(OUT, css);
      console.log(`design-css: ${css.split('\n').length} lines from the design`);
    }
  } catch (e) {
    console.error(e instanceof Error ? e.message : e);
    process.exit(2);
  }
}
